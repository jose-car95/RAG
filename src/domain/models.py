"""Data models exchanged between the stages of the RAG pipeline.

The eight models follow section VI.4 of the subject; ``MinimalSource`` adds
range checks on top of it.
"""

import uuid

from pydantic import BaseModel, Field, model_validator


class MinimalSource(BaseModel):
    """Location of a piece of text: a file and a character range.

    Indexes cannot be negative: in Python a negative index silently counts
    from the end of the file and would point at the wrong text.

    Attributes:
        file_path: Path of the file, exactly as in the corpus
            (``data/raw/vllm-0.10.1/...``).
        first_character_index: Position where the range starts (0-based).
        last_character_index: Position where the range ends.
    """

    file_path: str
    first_character_index: int = Field(ge=0)
    last_character_index: int = Field(ge=0)

    @model_validator(mode="after")
    def validate_range(self) -> "MinimalSource":
        """Reject a range that starts after it ends.

        Returns:
            The source itself, unchanged, when the range is valid.

        Raises:
            ValueError: If ``first_character_index`` is greater than
                ``last_character_index``.
        """
        if self.first_character_index > self.last_character_index:
            raise ValueError(
                "first_character_index must be less than or equal to "
                "last_character_index"
            )
        return self


class UnansweredQuestion(BaseModel):
    """A question without its solution.

    Attributes:
        question_id: Unique id; a new UUID is generated when it is missing.
        question: Text of the question.
    """

    question_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    question: str


class AnsweredQuestion(UnansweredQuestion):
    """A question together with its reference solution.

    Attributes:
        sources: Where the correct answer is in the corpus.
        answer: Reference answer text.
    """

    sources: list[MinimalSource]
    answer: str


class RagDataset(BaseModel):
    """A file of questions, with or without their solutions.

    Attributes:
        rag_questions: The questions; each one is answered or unanswered.
    """

    rag_questions: list[AnsweredQuestion | UnansweredQuestion]


class MinimalSearchResults(BaseModel):
    """Sources retrieved by our search for one question.

    Attributes:
        question_id: Id of the question that was searched.
        question: Text of the question.
        retrieved_sources: Sources found by the retriever, best first.
    """

    question_id: str
    question: str
    retrieved_sources: list[MinimalSource]


class MinimalAnswer(MinimalSearchResults):
    """Search results for one question plus the generated answer.

    Attributes:
        answer: Answer generated by the model from the retrieved sources.
    """

    answer: str


class StudentSearchResults(BaseModel):
    """Search output for a whole dataset, written by ``search_dataset``.

    Attributes:
        search_results: One entry per question.
        k: Number of sources requested per question.
    """

    search_results: list[MinimalSearchResults]
    k: int


class StudentSearchResultsAndAnswer(BaseModel):
    """Answer output for a whole dataset, written by ``answer_dataset``.

    Attributes:
        search_results: One entry per question, with its answer.
        k: Number of sources requested per question.
    """

    search_results: list[MinimalAnswer]
    k: int
